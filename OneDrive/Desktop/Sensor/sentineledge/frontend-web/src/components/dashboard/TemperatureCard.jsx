/**
 * src/components/dashboard/TemperatureCard.jsx
 * Hero stat card — current temperature + severity status.
 * All props are fully optional/null-safe.
 */
import { Thermometer, AlertTriangle, Clock } from 'lucide-react'
import { utcToIST, formatTime } from '../../utils/time.js'
import { getSeverityColor, getSeverityLabel, getTempColor, getTempBorderClass } from '../../utils/severity.js'
import Badge from '../shared/Badge.jsx'
import DashTile from './DashTile.jsx'
import useNow from '../../hooks/useNow.js'

function formatXlsTs(ts) {
  // ts from XLS has no timezone suffix → it's already IST from Pro-Server EX
  // ts from server has +00:00 or Z → needs UTC→IST conversion
  if (!ts) return null
  const hasZone = ts.includes('Z') || /[+-]\d{2}:\d{2}$/.test(ts)
  try {
    const d = hasZone ? new Date(ts) : new Date(ts + '+05:30')
    if (isNaN(d)) return ts
    return d.toLocaleString('en-IN', {
      day: '2-digit', month: 'short', year: 'numeric',
      hour: '2-digit', minute: '2-digit', second: '2-digit',
      hour12: true, timeZone: 'Asia/Kolkata',
    })
  } catch { return ts }
}

function relativeTime(ts) {
  if (!ts) return null
  try {
    const hasZone = ts.includes('Z') || /[+-]\d{2}:\d{2}$/.test(ts)
    const d = hasZone ? new Date(ts) : new Date(ts + '+05:30')
    if (isNaN(d)) return null
    const diffMs = Date.now() - d.getTime()
    const diffSec = Math.max(0, Math.floor(diffMs / 1000))
    const diffMin = Math.floor(diffMs / 60000)
    if (diffSec < 60) return { label: diffSec < 5 ? 'Just now' : `${diffSec}s ago`, stale: false }
    if (diffMin < 60) return { label: `${diffMin} min ago`, stale: diffMin > 5 }
    const diffH = Math.floor(diffMin / 60)
    if (diffH < 24)   return { label: `${diffH} hr ago`,    stale: true }
    return { label: `${Math.floor(diffH / 24)} day(s) ago`, stale: true }
  } catch { return null }
}

function severity2badge(s) {
  const m = { NORMAL:'green', WARNING:'amber', CRITICAL:'orange', EMERGENCY:'red' }
  return m[String(s ?? '').toUpperCase()] || 'green'
}

function collectorTime(ts) {
  // Extract HH:MM:SS.mmm from ISO string generated by collector (local time, no TZ suffix)
  if (!ts) return null
  const m = ts.match(/T(\d{2}:\d{2}:\d{2})\.(\d{3})/)
  if (m) return `${m[1]}.${m[2]}`
  return null
}

/**
 * `alert`    — the open (unacknowledged) temperature alert, or null. Colours and
 *              the breach line follow the alert, not the reading on screen, so
 *              the value keeps updating live and the red clears on acknowledge.
 * `blinking` — true only in the first 10 s after the alert fired.
 */
export default function TemperatureCard({ reading, thresholds, alert = null, blinking = false }) {
  // All properties safely extracted with defaults
  useNow()                                   // re-render every second so the age label counts live
  const temp      = reading?.temperature ?? null
  const ts        = reading?.timestamp   ?? null
  const seq       = reading?.sequence    ?? null
  const hasBreach = !!alert
  const sev       = alert?.severity || 'NORMAL'
  const sevUp     = String(sev).toUpperCase()
  const tempColor = hasBreach ? getTempColor(sev) : '#1F2937'

  const high = thresholds?.temperature?.high ?? 90
  const low  = thresholds?.temperature?.low  ?? 38

  const borderClass = hasBreach ? getTempBorderClass(sev) : ''
  const isEmergency = sevUp === 'EMERGENCY'

  // Truncate to 3 decimals without rounding (e.g. 20.08000183 → "20.080")
  const trunc3 = v => { const n = Number(v); return isNaN(n) ? '—' : (Math.trunc(n * 1000) / 1000).toFixed(3) }
  const displayTemp = typeof temp === 'number' ? trunc3(temp) : '—'
  const rel = ts ? relativeTime(ts) : null

  // Caption: reading timestamp + how old it is (amber when stale)
  const caption = ts ? (
    <span className="inline-flex items-center gap-1.5" title={collectorTime(ts) ? `Received ${collectorTime(ts)}` : undefined}>
      <Clock size={11} style={{ color: rel?.stale ? '#F59E0B' : '#6B7280', flexShrink: 0 }} />
      <span style={{ color: rel?.stale ? '#B45309' : undefined, fontWeight: rel?.stale ? 600 : 400 }}>
        {formatXlsTs(ts)}
      </span>
      {rel && (
        <span style={{
          fontSize: 10,
          color: rel.stale ? '#D97706' : '#9CA3AF',
          background: rel.stale ? '#FEF3C7' : '#F3F4F6',
          borderRadius: 4, padding: '1px 5px', fontWeight: 500,
        }}>
          {rel.label}
        </span>
      )}
    </span>
  ) : (reading ? 'No timestamp on reading' : 'Connecting to sensor…')

  return (
    <DashTile
      icon={Thermometer}
      iconColor="#8B5CF6"
      label="Temperature"
      badge={
        <Badge
          color={severity2badge(sev)}
          label={hasBreach ? String(getSeverityLabel(sev)).toUpperCase() : 'NORMAL'}
          pulse={blinking}
        />
      }
      value={typeof temp === 'number' ? displayTemp : (alert ? trunc3(alert.latestValue) : null)}
      valueColor={tempColor}
      valueKey={displayTemp}
      unit="°C"
      caption={caption}
      footerLeft={`Normal: ${low}°C – ${high}°C`}
      footerRight={seq != null ? `Collector #${seq}` : (ts ? utcToIST(ts) : 'No data yet')}
      className={`${borderClass} ${isEmergency && blinking ? 'animate-flash-red' : ''}`}
    >
      {/* Breach line — exact value and time the alert fired */}
      {hasBreach && (
        <div
          className="flex items-center gap-2 px-3 py-2 rounded-lg"
          style={{ background: getSeverityColor(sev)?.bg ?? '#FEF2F2' }}
        >
          <AlertTriangle size={14} style={{ color: getSeverityColor(sev)?.dot ?? '#EF4444', flexShrink: 0 }} />
          <span className="text-xs font-semibold" style={{ color: getSeverityColor(sev)?.text ?? '#991B1B' }}>
            {alert.direction === 'low' ? 'Below' : 'Above'} threshold — {trunc3(alert.value)}°C at {formatTime(alert.firedAt)}
          </span>
        </div>
      )}
    </DashTile>
  )
}
